"""Generates MODLIST.md from the jars in mods/ (run after adding, removing or updating a mod).

Usage (from the instance folder): python tools/modlist.py
"""
import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODS = ROOT / "mods"


def read_mod(jar):
    with zipfile.ZipFile(jar) as zf:
        names = zf.namelist()
        toml = zf.read("META-INF/mods.toml").decode("utf-8", "replace") if "META-INF/mods.toml" in names else ""
        manifest = zf.read("META-INF/MANIFEST.MF").decode("utf-8", "replace") if "META-INF/MANIFEST.MF" in names else ""
    block = toml.split("[[mods]]", 1)[1] if "[[mods]]" in toml else ""
    get = lambda key: (re.search(rf'^\s*{key}\s*=\s*"([^"]*)"', block, re.M) or [None, None])[1]
    mod_id, name, version = get("modId"), get("displayName"), get("version")
    if not version or "${" in version:
        version = (re.search(r"^Implementation-Version:\s*(\S+)", manifest, re.M) or [None, None])[1]
    return mod_id or "?", name or jar.stem, version or "?"


def main():
    rows = sorted((read_mod(jar) + (jar.name,) for jar in MODS.glob("*.jar")), key=lambda r: r[1].lower())
    lines = [
        "# Mod list",
        "",
        f"{len(rows)} mods. Generated by `tools/modlist.py` - do not edit by hand.",
        "",
        "| Mod | Mod id | Version | File |",
        "|---|---|---|---|",
    ]
    lines += [f"| {name} | `{mod_id}` | {version} | `{file}` |" for mod_id, name, version, file in rows]
    (ROOT / "MODLIST.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"MODLIST.md: {len(rows)} mods")


if __name__ == "__main__":
    main()
